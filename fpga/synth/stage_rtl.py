#!/usr/bin/env python3
"""Stage the RTL that actually ships, for the yosys synthesis gate.

Why this exists
---------------
`fpga/rtl/` is the source of record and stays byte-identical, but it is not
what gets flashed: `fpga/qmtech/build_bitstream_qmtech.tcl` synthesises a
*patched* copy of it, and that patched copy is the configuration that closes
timing on the real XC7A15T board (build/qssc_qmtech.bit).  Synthesising the
raw files instead would gate a configuration nobody ships -- the raw
`command_parser.v` costs 8738 CARRY4 (168 % of an XC7A35T) purely from its
combinational decimal formatters, while the patched tree needs ~784.

This script reproduces, outside Vivado, exactly what the Tcl does:

  1. rtl/top_level.v   -> build/top_level_xc7.v   (ODDR2 -> plain assign)
                       -> build/top_level_final.v (patch_top_gate: /10 delay)
  2. rtl/command_parser.v -> command_parser_gate -> _fmt -> _div -> _wait
     (patch_gate_cmd, patch_formatters, patch_div_seq, patch_fsm_wait)
  3. rtl/adf4351_ctrl.v   -> adf4351_ctrl_wait.v   (patch_pll_wait)

Nothing under fpga/rtl/ is written to; every output lands in the gitignored
fpga/qmtech/build/ directory, which is also where the Vivado flow writes them.

Run it directly, or let `fpga/synth/run_synth.sh` call it before yosys:

    python3 fpga/synth/stage_rtl.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RTL = ROOT / "fpga" / "rtl"
QMTECH = ROOT / "fpga" / "qmtech"
BUILD = QMTECH / "build"

# Same anchor the Vivado Tcl uses: the ODDR2 instance that drives refclk_out.
ODDR2_INST = re.compile(r"ODDR2\s*#.*?\.Q\s*\(refclk_out\)\)\s*;", re.S)
ODDR2_REPLA = (
    "assign refclk_out = refclk_25m;  // XC7 PATCH: ODDR2 (Spartan-6) -> plain flop"
)

# (script, output) in the order the Tcl runs them.
PATCH_CHAIN = [
    ("patch_top_gate.py", "top_level_final.v"),
    ("patch_gate_cmd.py", "command_parser_gate.v"),
    ("patch_formatters.py", "command_parser_fmt.v"),
    ("patch_div_seq.py", "command_parser_div.v"),
    ("patch_pll_wait.py", "adf4351_ctrl_wait.v"),
    ("patch_fsm_wait.py", "command_parser_wait.v"),
]


def stage() -> list[Path]:
    BUILD.mkdir(parents=True, exist_ok=True)

    # 1. top_level: ODDR2 -> assign, then the gate-delay second pass.
    src = (RTL / "top_level.v").read_text(encoding="utf-8")
    if not ODDR2_INST.search(src):
        if "ODDR2" in src:
            raise SystemExit(
                "top_level.v contains ODDR2 but the patch anchor did not match -- "
                "review the instance by hand (the Tcl uses the same anchor)."
            )
        xc7 = src  # already migrated to ODDR; stage as-is
    else:
        xc7 = ODDR2_INST.sub(ODDR2_REPLA, src, count=1)
    (BUILD / "top_level_xc7.v").write_text(
        "// Generated by fpga/synth/stage_rtl.py -- DO NOT EDIT\n"
        "// Patched copy of rtl/top_level.v (original never written to)\n" + xc7,
        encoding="utf-8",
    )

    # 2/3. the patch chain (each script reads a fixed input, writes build/)
    for script, out in PATCH_CHAIN:
        res = subprocess.run(
            [sys.executable, str(QMTECH / script)],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
        )
        if res.returncode != 0:
            raise SystemExit(
                f"{script} failed (rc={res.returncode}):\n{res.stdout}\n{res.stderr}"
            )
        target = BUILD / out
        if not target.is_file():
            raise SystemExit(f"{script} did not produce {target}")

    outputs = [BUILD / "top_level_final.v",
               BUILD / "command_parser_wait.v",
               BUILD / "adf4351_ctrl_wait.v"]
    print(f"staged {len(outputs)} patched files into {BUILD.relative_to(ROOT)}/")
    for p in outputs:
        print(f"  {p.relative_to(ROOT)}  ({len(p.read_text(encoding='utf-8').splitlines())} lines)")
    return outputs


if __name__ == "__main__":
    stage()
